#!/usr/bin/env node
/**
 * Copy the pure money/ledger modules into the React Native app.
 *
 * These files have no DOM dependencies, and both apps must agree to the paise,
 * so they are generated rather than reimplemented. Run after changing any of
 * them:  node scripts/sync-native-logic.mjs
 */
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const target = join(root, 'mobile', 'src', 'lib')

const files = [
  ['src/types.ts', 'types.ts'],
  ['src/lib/money.ts', 'money.ts'],
  ['src/lib/splits.ts', 'splits.ts'],
  ['src/lib/balances.ts', 'balances.ts'],
  ['src/lib/settlement.ts', 'settlement.ts'],
  ['src/lib/receipt.ts', 'receipt.ts'],
  ['src/lib/voice.ts', 'voice.ts'],
  ['src/lib/billParser.ts', 'billParser.ts'],
]

const banner = `// GENERATED by scripts/sync-native-logic.mjs — edit the source in src/lib instead.\n`

await mkdir(target, { recursive: true })
for (const [from, to] of files) {
  const source = await readFile(join(root, from), 'utf8')
  // The web modules import the shared model from ../types; in the app it sits
  // beside them.
  const rewritten = source.replace(/from '\.\.\/types'/g, "from './types'")
  await writeFile(join(target, to), banner + rewritten)
  console.log(`synced ${from} -> mobile/src/lib/${to}`)
}

// upi.ts has no DOM dependency either, so the native app shares it too.
await copyFile(join(root, 'src/lib/upi.ts'), join(target, 'upi.ts')).catch(() => undefined)
console.log('done')
